def run_inquisitor_checks(rad, v_obs, v_theory, err_v, g_bar, tau):
    """
    Параллельно обсчитывает три физических чека консервативности полей для каждого кольца dR.
    """
    # Имитация послойного аудита (Теорема Нётер и импульс)
    # Вычисляем пространственный ротор (разность между соседними точками радиуса)
    delta_r = np.diff(rad, append=rad[-1] + 0.1)
    delta_v = np.diff(v_theory, append=v_theory[-1])
    
    # 1. Чек сохранения импульса (баланс центростремительных сил)
    p_check = np.abs(v_obs**2 / (rad + 1e-8) - v_theory**2 / (rad + 1e-8)) < err_v
    
    # 2. Чек сохранения энергии (утечка в пустоту алгоритма)
    e_check = np.abs(delta_v / (delta_r + 1e-8)) < 5.0 # Производная потенциала гладкая
    
    # 3. Консервативность поля (отсутствие вечных двигателей)
    field_check = np.all(tau >= 0.0) and np.all(tau <= 1.0) # Сигмоида строго зажата в ОДЗ [0, 1]
    
    if not (np.all(p_check) and np.all(e_check) and field_check):
        return "Варнинг: Искрение поля! Перенаправлено в ОДЗ-коридор"
    return "Честный ноль СИ: Законы сохранения ОК"


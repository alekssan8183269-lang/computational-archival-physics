plt.plot(t, y_base, color='#2C3E50', linestyle=':', linewidth=1.5, zorder=1)

# Перебираем каждую точку данных и рисуем для нее кастомный кинетический след
for i in range(1, len(t)):
    # Рассчитываем вектор движения метеора (скорость изменения)
    dt = t[i] - t[i-1]
    dy = y_base[i] - y_base[i-1]
    
    # Задаем длину и направление хвоста метеора (инвертируем вектор движения)
    tail_length = 4.0 * tau_lag[i] # При лаге хвост сильно удлиняется и горит
    x_tail = np.linspace(t[i], t[i] - dt * tail_length, 20)
    y_tail = np.linspace(y_base[i], y_base[i] - dy * tail_length, 20)
    
    # Цветовой градиент хвоста: от синего (холодный/стабильный) к огненно-красному (аварийный)
    # Используем палитру 'coolwarm' или 'jet'
    color_val = plt.cm.jet(tau_lag[i])
    
    # Рисуем плавно затухающий хвост метеора
    for j in range(len(x_tail)-1):
        alpha_fade = 0.8 * (1.0 - j / len(x_tail)) # Хвост тает к концу
        plt.plot(x_tail[j:j+2], y_tail[j:j+2], color=color_val, 
                 linewidth=3.0 * alpha_fade, alpha=alpha_fade, zorder=2)
        
    # Если лаг \tau велик, метеор начинает сбрасывать "искры шума" вокруг себя
    if tau_lag[i] > 0.4:
        num_sparks = int(tau_lag[i] * 15)
        spark_x = t[i] + np.random.uniform(-0.15, 0.15, num_sparks)
        spark_y = y_base[i] + np.random.uniform(-0.25, 0.25, num_sparks)
        plt.scatter(spark_x, spark_y, color='#F39C12', s=shum_sparks[i]*25, 
                    alpha=0.5, edgecolors='none', zorder=3)

# Накладываем сами светящиеся головы метеоров поверх хвостов
# Размер головы (s) завязан на массу/значимость точки, цвет — на стабильность
scatter_heads = plt.scatter(t, y_base, c=tau_lag, cmap='jet', s=50, 
                            edgecolors='white', linewidths=0.8, zorder=4)

# Оформление интерфейса в космическом научно-исследовательском стиле
plt.grid(True, color='#1A2536', linestyle='--', alpha=0.5)
plt.title('График-«Метеор»: Кинетический след потока данных и испускание искр под действием лага $\\tau$', 
          fontsize=14, fontweight='bold', pad=15, color='#E2E8F0')
plt.xlabel('Время процесса ($t$)', fontsize=11, fontweight='bold', color='#94A3B8')
plt.ylabel('Метрологический отклик системы', fontsize=11, fontweight='bold', color='#94A3B8')
ax.tick_params(colors='#94A3B8') # Цвет делений на осях

# Цветовая шкала для понимания температуры лага \tau
cb = plt.colorbar(scatter_heads)

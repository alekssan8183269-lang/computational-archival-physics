# --- ПРОЦЕССОР 1: Голый Ньютон / Эйнштейн ---
def processor_1_newton(rad, v_gas, v_disk):
    """
    Вычисляет чистый барионный профиль по Казертано без привлечения скрытых масс.
    """
    # Математика послойной интеграции распределенной массы плоского блинчика
    g_bar = (v_gas**2 + v_disk**2) / (rad + 1e-8)
    v_theory = np.sqrt(np.abs(g_bar) * rad)
    return v_theory

# --- ПРОЦЕССОР 2: Тёмная Материя (Профиль NFW и Burkert) ---
def nfw_halo_profile(r, rho_0, r_s):
    """Каноническая икона мейнстрима с куспидной сингулярностью в нуле."""
    return rho_0 / ((r / r_s) * (1 + r / r_s)**2 + 1e-8)

def burkert_halo_profile(r, rho_0, r_c):
    """Запасной костыль мейнстрима с бесконечным ростом массы на бесконечности."""
    return rho_0 / (1 + (r / r_c)**2 + 1e-8)

def processor_2_dark_matter(rad, v_obs, err_v, v_theory_base):
    """
    Оптимизатор SciPy (L-BFGS-B) подгоняет виртуальные килограммы гало Тёмной материи.
    """
    def dm_loss(params):
        rho_0, r_scale = params
        # Считаем вклад скрытой массы в скорость (V^2 = V_base^2 + G*M_dark/R)
        # Для простоты аппроксимируем интеграл профиля NFW
        v_dark = np.sqrt(np.abs(rho_0 * rad / (1 + rad / r_scale)))
        v_total = np.sqrt(v_theory_base**2 + v_dark**2)
        return np.sum(((v_obs - v_total) / err_v) ** 2)
    
    res = minimize(dm_loss, [0.1, 5.0], method='L-BFGS-B', 
                   bounds=[(1e-5, None), (0.1, 50.0)], options={'ftol': 1e-9, 'gtol': 1e-9})
    
    rho_opt, r_opt = res.x
    v_dark_opt = np.sqrt(np.abs(rho_opt * rad / (1 + rad / r_opt)))
    return np.sqrt(v_theory_base**2 + v_dark_opt), res.success

# --- ПРОЦЕССОР 3: Модифицированная Гравитация MOND Милгрома ---
def processor_3_mond(rad, g_bar):
    """
    Алгоритм Милгрома с фиксированной константой а0. Без учета эффекта внешнего поля EFE.
    """
    a0 = 1.2e-10 # Критическое ускорение СИ
    # Математика нелинейного перехода MOND
    g_mond = g_bar / np.sqrt(1.0 + (a0 / (g_bar + 1e-12))**2)
    v_theory = np.sqrt(np.abs(g_mond) * rad)
    return v_theory

# --- ПРОЦЕССОР 4: Вязкоупругий Вакуум СТТМ (Наше расчетное ядро v3.0) ---
def sttm_sigmoid_tau(g_bar, beta, g0=1.2e-10):
    """Непрерывная сигмоида лага релаксации тау без ручных if-else заглушек."""
    return 1.0 / (1.0 + np.exp(-beta * (g_bar - g0)))

def processor_4_sttm(rad, v_obs, err_v, g_bar, v_theory_base):
    """
    Инквизиторский подгон параметра упругости бегущего вакуума бета.
    """
    def sttm_loss(beta_param):
        tau = sttm_sigmoid_tau(g_bar, beta_param[0])
        # Упругий подпор Колеи компенсирует падение ньютоновской силы
        v_sttm = v_theory_base * (1.0 + (1.0 - tau) * 1.5)
        return np.sum(((v_obs - v_sttm) / err_v) ** 2)
    
    res = minimize(sttm_loss, [0.25], method='L-BFGS-B', 
                   bounds=[(0.01, 10.0)], options={'ftol': 1e-9, 'gtol': 1e-9})
    
    beta_opt = res.x[0]
    tau_opt = sttm_sigmoid_tau(g_bar, beta_opt)
    return v_theory_base * (1.0 + (1.0 - tau_opt) * 1.5), res.success, beta_opt, tau_opt


import matplotlib.pyplot as plt

# 1. ГЕНЕРИРУЕМ ВРЕМЕННУЮ СЕТКУ И ИДЕАЛЬНЫЙ СИГНАЛ
np.random.seed(42) # Чтобы генерация шума всегда была одинаковой
t = np.linspace(0, 10, 500)
# Идеальная теоретическая модель (например, затухающая синусоида)
y_ideal = np.sin(2 * np.pi * t * 0.5) * np.exp(-t * 0.1)

# 2. МОДЕЛИРУЕМ ИЗМЕНЕНИЕ ПОГРЕШНОСТИ (Аналог лага \tau)
# Пусть в начале и конце процесса прибор точен, а в центре (t=5) шум дико растет
pogreshnost = 0.05 + 0.35 * np.exp(-(t - 5)**2 / 2.0)

# 3. ГЕНЕРИРУЕМ КВАНТОВОЕ ОБЛАКО ТОЧЕК (МАТРИЦА ВЕРОЯТНОСТЕЙ)
# Для каждой точки времени создаем по 150 случайных микро-точек вокруг нее
num_particles_per_point = 150
t_cloud = []
y_cloud = []
alpha_cloud = [] # Прозрачность точек

for i in range(len(t)):
    # Распределяем точки вокруг идеальной линии по закону Гаусса (нормальное распределение)
    # Ширина распределения напрямую зависит от метрологической погрешности в этот миг
    deviations = np.random.normal(loc=0, scale=pogreshnost[i], size=num_particles_per_point)
    
    t_cloud.extend([t[i]] * num_particles_per_point)
    y_cloud.extend(y_ideal[i] + deviations)
    
    # Магия визуализации: чем дальше точка от идеала, тем она прозрачнее
    # Это создает эффект настоящего размытого энергетического облака
    density = np.exp(-deviations**2 / (2 * pogreshnost[i]**2))
    alpha_cloud.extend(density * 0.15) # 0.15 - базовая яркость облака

# Переводим списки в массивы NumPy для быстрой отрисовки
t_cloud = np.array(t_cloud)

# Длина хвоста показывает скорость изменения параметров.Направление изгиба хвоста — куда систему потянет в следующий миг (вектор предсказания).
# Когда лаг τ и шум в CSV-файле начинают расти, хвост метеора окрашивается в огненно-красный цвет и начинает «взрываться», распадаясь на хаотичные искры (шум).

import numpy as np
import matplotlib.pyplot as plt

# 1. ГЕНЕРИРУЕМ ВРЕМЕННУЮ СЕТКУ И ИСХОДНУЮ ТРАЕКТОРИЮ
np.random.seed(55)
t = np.linspace(0, 10, 80) # 80 ключевых точек-метеоров
y_base = 2.0 * np.log(t + 1) + np.sin(t) # Базовый физический тренд

# 2. МОДЕЛИРУЕМ ПАРАМЕТРЫ МЕТЕОРНОГО ХВОСТА ИЗ ДАННЫХ CSV
# Пусть в районе t = 4.0 и t = 8.0 у нас происходят жесткие скачки лага \tau
tau_lag = 0.1 + 0.8 * np.exp(-(t - 4.0)**2 / 0.8) + 0.9 * np.exp(-(t - 8.0)**2 / 1.2)
shum_sparks = np.random.rand(len(t)) * tau_lag * 0.4 # Искры шума зависят от лага

# 3. ПОСТРОЕНИЕ ГРАФИКА «МЕТЕОР»
plt.figure(figsize=(13, 8), facecolor='white')
ax = plt.gca()
ax.set_facecolor('#0B0F19') # Глубокий космический черный цвет для контраста хвостов


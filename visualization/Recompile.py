# Но как только лаг τ или каскадный шум начинают расти, ветки в этой точке данных начинают резко ломаться под неестественными углами, 
# дробиться на уродливые сучки и окрашиваться в аварийный красный цвет.
# Учёный мгновенно видит, где именно зародилась ошибка и как она «пустила метастазы» (каскадные сбои) по всей системе.

import numpy as np
import matplotlib.pyplot as plt

# 1. СИМУЛЯЦИЯ CSV-ДАННЫХ (Цепочка каскадных ошибок)
np.random.seed(42)
num_steps = 120  # Количество шагов измерения в файле
t = np.linspace(0, 10, num_steps)

# Моделируем нарастание лага \tau ближе к концу эксперимента
tau_lag = 0.1 + 0.9 / (1 + np.exp(-(t - 6.5) / 0.8))
# Шум начинает хаотично дробиться (каскадный сбой), когда лаг велик
cascade_noise = np.random.randn(num_steps) * (tau_lag ** 2)

# 2. МАТЕМАТИКА ФРАКТАЛЬНОГО ДЕРЕВА
fig, ax = plt.subplots(figsize=(12, 9), facecolor='white')
ax.set_facecolor('#FDFDFD')

def draw_branch(x, y, angle, length, depth, step_idx):
    """
    Рекурсивная функция для отрисовки фрактальных веток сбоев.
    """
    if depth == 0 or step_idx >= num_steps:
        return
    
    # Считываем текущее состояние метрологии из данных
    current_tau = tau_lag[step_idx]
    current_noise = cascade_noise[step_idx]
    
    # Задаем цвет ветки: от здорового зеленого до аварийного красного
    if current_tau < 0.3:
        color = '#27AE60'  # Стабильно (зеленый)
        linewidth = depth * 1.2
    elif current_tau < 0.6:
        color = '#F39C12'  # Внимание (оранжевый)
        linewidth = depth * 1.0
    else:
        color = '#C0392B'  # КРИТИЧЕСКИЙ СБОЙ (красный)
        linewidth = depth * 0.7  # Ошибка истощает устойчивость ветки
        
    # Рассчитываем конечную точку текущей ветки
    # Ошибка искажает угол (angle) и длину (length) фрактального сегмента
    angle_distortion = current_noise * 0.45  # Чем выше шум, тем сильнее гнутся ветки
    length_loss = length * (1.0 - current_tau * 0.3)  # Лаг укорачивает стабильный рост
    
    x_end = x + length_loss * np.cos(angle + angle_distortion)
    y_end = y + length_loss * np.sin(angle + angle_distortion)
    
    # Рисуем сегмент ветки
    ax.plot([x, x_end], [y, y_end], color=color, linewidth=linewidth, solid_capstyle='round', zorder=depth)
    
    # Фрактальное разветвление: дерево делится на два новых побега
    # Идеальный угол деления — около 25-30 градусов (0.45 радиан)
    spread = 0.45 + (current_tau * 0.2)  # При лаге ветки растопыриваются в панике
    
    # Рекурсивный запуск следующих уровней дерева (идем вглубь)
    next_step = step_idx + 1
    draw_branch(x_end, y_end, angle + spread, length_loss * 0.75, depth - 1, next_step)
    draw_branch(x_end, y_end, angle - spread, length_loss * 0.75, depth - 1, next_step)

# 3. ЗАПУСК РОСТА ДЕРЕВА ИЗО ДНЯ ДАННЫХ
# Начинаем из корня (0,0), растем строго вверх (угол pi/2), глубина рекурсии 10 уровней
start_x, start_y = 0.0, 0.0
initial_angle = np.pi / 2
initial_length = 2.0
max_depth = 10

draw_branch(start_x, start_y, initial_angle, initial_length, max_depth, step_idx=0)

# 4. ОФОРМЛЕНИЕ ИНТЕРФЕЙСА
ax.axis('off')  # Отключаем скучные оси координат, это же живое дерево!
plt.title('График «Фрактальное Дерево Сбоев»: Каскадное разрушение структуры под действием лага $\\tau$', 
          fontsize=14, fontweight='bold', pad=20, color='#2C3E50')

# Создаем кастомную легенду-подсказку для ученых
import matplotlib.patches as mpatches
green_patch = mpatches.Patch(color='#27AE60', label='Система стабильна (Лаг $\\tau$ в норме)')
orange_patch = mpatches.Patch(color='#F39C12', label='Превышение допуска (Дрейф параметров)')
red_patch = mpatches.Patch(color='#C0392B', label='Каскадный сбой (Разрушение связей)')

# 3. ФУНКЦИЯ ДЛЯ ОТРИСОВКИ КРИСТАЛЛА
def draw_crystal(ax, data, title, is_defect=False):
    # Вытягиваем вершины пропорционально ошибкам из данных
    # Новая координата = Базовая координата * (1 + Ошибка * Коэффициент_роста)
    scaled_vertices = base_vertices * (1.0 + data[:, np.newaxis] * 1.5)
    
    # Собираем 3D-полигоны для граней
    poly3d = [[scaled_vertices[vert] for vert in face] for face in faces]
    
    # Выбираем цвет: зеленый для нормы, красный для брака
    face_color = (0.9, 0.2, 0.2, 0.6) if is_defect else (0.2, 0.8, 0.2, 0.6)
    edge_color = (0.5, 0.1, 0.1, 1.0) if is_defect else (0.1, 0.4, 0.1, 1.0)
    
    # Рисуем объект на 3D сцене
    mesh = Poly3DCollection(poly3d, facecolors=face_color, edgecolors=edge_color, linewidths=1.5)

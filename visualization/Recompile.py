from matplotlib import cm
from scipy.interpolate import griddata

# 1. СИМУЛЯЦИЯ СТРУКТУРЫ БАЗЫ ДАННЫХ SPARC (175 ГАЛАКТИК)
np.random.seed(175)
num_galaxies = 175

# Параметр X: Светимость Spitzer 3.6 мкм (логарифм массы звезд от 7 до 12 L_sun)
log_L36 = np.random.uniform(7.0, 12.0, num_galaxies)
# Параметр Y: Эффективный радиус галактического диска (от 0.3 до 15 кпк)
R_eff = np.random.uniform(0.3, 15.0, num_galaxies)

# Рассчитываем идеальную скорость вращения по закону Талли-Фишера (Baryonic Tully-Fisher)
# В стабильном мире скорость жестко привязана к светимости
V_flat_ideal = 2.5 * log_L36 + 1.2 * np.log10(R_eff)

# МОДЕЛИРУЕМ ТЕ САМЫЕ "УЛЕТАЮЩИЕ" АНОМАЛЬНЫЕ ТОЧКИ В КИНЕМАТИКЕ
# В реальности именно эти выбросы заставляют ученых спорить о Темной Материи!
anomaly_metric = np.zeros(num_galaxies)
for i in range(num_galaxies):
    # Если галактика маленькая и тусклая (карликовая Irr), у нее сильный дефицит барионов
    if log_L36[i] < 9.0 and R_eff[i] > 8.0:
        anomaly_metric[i] = np.random.uniform(2.5, 4.5) # Жесткий выброс вверх
    # Если галактика огромная, но имеет низкую поверхностную яркость (LSB)
    elif log_L36[i] > 10.5 and R_eff[i] > 12.0:
        anomaly_metric[i] = np.random.uniform(2.0, 3.8) # Тоже улетает
    else:
        anomaly_metric[i] = np.random.uniform(0.0, 0.8) # Спокойная норма

# Реальная скорость с учетом аномалий
V_flat_observed = V_flat_ideal + anomaly_metric * 15.0

# 2. МАТЕМАТИКА ЛАНДШАФТА (Интерполяция 175 точек в непрерывное 3D поле)
grid_x, grid_y = np.mgrid[7.0:12.0:100j, 0.3:15.0:100j]
# Создаем упругую трехмерную поверхность "гравитационных аномалий"
grid_z = griddata((log_L36, R_eff), anomaly_metric, (grid_x, grid_y), method='cubic')
grid_z = np.nan_to_num(grid_z) # Убираем пустые зоны по краям

# 3. ПОСТРОЕНИЕ 3D ГРАФИКА «ГРАВИТАЦИОННЫЙ ЛАНДШАФТ ПОТЕРЬ»
fig = plt.figure(figsize=(14, 10), facecolor='white')
ax = fig.add_subplot(111, projection='3d')

# Рисуем топографический рельеф. Палитра 'terrain' переведет ошибки в форму гор
surf = ax.plot_surface(grid_x, grid_y, grid_z, cmap='terrain', alpha=0.6,
                       linewidth=0.1, antialiased=True, zorder=1)

# Накладываем сверху реальные 175 галактик в виде метеоров со стрелками!
# Направление стрелки показывает, КУДА и с какой силой галактика улетает от нормы
u_anomaly = np.zeros_like(log_L36)
v_anomaly = np.zeros_like(R_eff)
w_anomaly = anomaly_metric * 0.8 # Вектор роста ошибки вверх

# Отрисовываем стрелки векторов аномалии для каждой из 175 галактик
ax.quiver(log_L36, R_eff, anomaly_metric, u_anomaly, v_anomaly, w_anomaly,
          color='black', alpha=0.8, arrow_length_ratio=0.15, linewidths=1.0, zorder=3)

# Подсвечиваем сами галактики яркими точками (цвет завязан на тяжесть аномалии)
sc = ax.scatter(log_L36, R_eff, anomaly_metric, c=anomaly_metric, cmap='jet',
                s=40, edgecolors='black', linewidths=0.5, alpha=0.9, zorder=4)

# Оформление интерфейса в строгом научном стиле
ax.set_title('SPARC Database: 3D Ландшафт Гравитационных Аномалий (175 галактик)\nВизуализация скрытых барионных потерь без внешних параметров', 
             fontsize=13, fontweight='bold', pad=20)
ax.set_xlabel(r'Светимость Spitzer [3.6 $\mu$m] (log $L_{\odot}$)', fontsize=10, fontweight='bold', labelpad=10)
ax.set_ylabel(r'Эффективный радиус диска $R_{eff}$ (кпк)', fontsize=10, fontweight='bold', labelpad=10)
ax.set_zlabel('Индекс гравитационного ухода (Выброс скорости)', fontsize=10, fontweight='bold', labelpad=10)

# Настраиваем красивый угол обзора, чтобы рельеф гор был виден идеально
ax.view_init(elev=28, azim=-125)

# Добавляем цветовую шкалу для понимания критичности выброса
cb = fig.colorbar(sc, ax=ax, shrink=0.5, aspect=15)
cb.set_label('Величина отклонения от закона Талли-Фишера', fontsize=10, fontweight='bold', labelpad=10)

plt.tight_layout()
plt.show()
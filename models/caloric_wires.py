import numpy as np

# ==============================================================================
# МОДУЛЬ: Caloric-Wires-Optimization (Вектор 2 фреймворка RE-PHYSICS)
# ЭПИСТЕМЕ: Согласно теории теплорода (Карно/Лавуазье), тепло — это невесомый флюид.
# Мы применяем "Математическое моделирование флюидных потоков" (CaloricDescent).
# Наша цель — вырастить внутри жесткого диэлектрика (Алмаз/Рубин) идеальный проводящий 
# канал из атомов Серы. Мы пускаем флюид теплорода сквозь матрицу. Если Сера 
# разбросана хаотично, флюид застревает (перегрев -> удар током). Если Сера 
# выстраивается в идеальный непрерывный капилляр, теплород летит без потерь.
# ==============================================================================

class CaloricWiresSimulator:
    def __init__(self, grid_size=10):
        """Создаем линейное пространство минерала из 10 узлов (атомарная нить)"""
        self.grid_size = grid_size
        # Задаем "калорическое сопротивление" теплороду:
        # Алмаз (C) и Рубин (Al) сопротивляются флюиду, Сера (S) — идеальный проводник флюида
        self.resistance_map = {'C': 5.0, 'Al': 8.0, 'S': 0.1}

    def simulate_caloric_descent(self, atom_chain):
        """
        Реализует Тензорную оптимизацию хаотических систем и Стохастический фильтр.
        atom_chain: список из 10 атомов, предложенный компьютером (например, ['C', 'S', 'C'...])
        """
        n = self.grid_size
        
        # 1. Строим вектор калорического сопротивления для текущей цепочки
        r_vector = np.array([self.resistance_map[atom] for atom in atom_chain])
        
        # 2. Инициализируем флюид теплорода: на входе (узел 0) давление максимальное (100.0)
        # На выходе (узел n-1) давление равно 0. Мы симулируем течение
        caloric_pressure = np.zeros(n)
        caloric_pressure[0] = 100.0
        
        # Запускаем гидродинамику теплорода (моделируем перетекание под давлением градиента)
        # 20 итераций для стабилизации потока флюида
        for _ in range(20):
            for i in range(1, n - 1):
                # Поток теплорода зависит от разницы давлений и сопротивления соседей
                grad_left = (caloric_pressure[i-1] - caloric_pressure[i]) / (r_vector[i-1] + r_vector[i])
                grad_right = (caloric_pressure[i] - caloric_pressure[i+1]) / (r_vector[i] + r_vector[i+1])
                
                # Обновляем давление в узле согласно балансу флюида Юнга-Дюпре
                caloric_pressure[i] += (grad_left - grad_right) * 0.5

        # 3. МЕТОД ЦИФРОВЫХ ПУСТОТ: Анализируем лакуны и заторы флюида
        shock_voltage = 0.0
        total_flow = 0.0
        
        # Считаем результирующий поток теплорода на выходе из нити
        final_flow = (caloric_pressure[n-2] - caloric_pressure[n-1]) / (r_vector[n-2] + r_vector[n-1])
        
        # ⚡️ ШТРАФ 1: Затор флюида. Если атомы Серы прерываются Алмазом, 
        # давление резко падает (затор). Шарахаем ПК током за каждую заблокированную зону!
        for i in range(1, n):
            drop = caloric_pressure[i-1] - caloric_pressure[i]
            if drop > 15.0: # Слишком резкий перепад давлений теплорода
                shock_voltage += drop * 250
                
        # 💎 ЧИТЕРСКИЙ БОНУС: Мы максимизируем сквозной поток (final_flow).
        # Чем выше поток флюида, тем меньше штрафной вольтаж!
        shock_voltage -= final_flow * 300
        
        # Ограничиваем нижний порог вольтажа нулем
        shock_voltage = max(0.0, shock_voltage)
        
        return shock_voltage, final_flow, caloric_pressure


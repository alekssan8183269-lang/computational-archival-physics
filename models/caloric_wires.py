if __name__ == "__main__":
    print("🌀 RE-PHYSICS: Запуск Вектора 2 (Потоки теплорода Карно / CaloricDescent)")
    print("🧪 Цель: Заставить Серу вырасти в идеальный атомарный провод внутри Алмаза")
    
    simulator = CaloricWiresSimulator(grid_size=10)
    
    # Пул доступных атомов для синтеза нити (Ограниченное количество Серы)
    available_pool = ['C', 'C', 'C', 'C', 'Al', 'Al', 'S', 'S', 'S', 'S']
    
    best_chain = None
    min_shock = float('inf')
    max_achieved_flow = 0.0
    
    # 5000 шагов жесткого отбора под напряжением
    for step in range(1, 5001):
        # Компьютер случайно перемешивает атомы в цепочке, пытаясь угадать мотив
        test_chain = list(np.random.choice(available_pool, size=10, replace=False))
        
        # Пропускаем через архивный фильтр теплорода
        shock, flow, pressure_map = simulator.simulate_caloric_descent(test_chain)
        
        # Если структура лучше проводит флюид и получает меньше тока — фиксируем
        if shock < min_shock:
            min_shock = shock
            best_chain = test_chain
            max_achieved_flow = flow
            print(f"Шаг {step}: Нить перестроилась! Ток: {shock:.1f} V | Пропуск флюида: {flow:.2f}")
            
            # Если нашли идеальный мотив капилляра (0 вольт) — стоп!
            if min_shock == 0:
                break
                
    print("\n🎉 Оптимизация Вектора 2 завершена!")
    print(f"Идеальная топология читерского провода: {best_chain}")
    print(f"Финальная скорость протекания теплорода: {max_achieved_flow:.4f}")
    print(f"Финальный пробой тока системы: {min_shock:.2f} V")

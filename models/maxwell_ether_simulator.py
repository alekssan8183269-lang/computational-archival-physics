# Создаем Модуль B: «Maxwell-Ether» (Механический эфир Максвелла).
# В 1861 году Джеймс Максвелл опубликовал работу «On Physical Lines of Force», 
# где представил вакуум как плотную упругую среду, состоящую из крошечных вращающихся ячеек-вихрей. 
# Их вращение описывается псевдовекторами угловой скорости. 
# Чтобы ячейки не тёрлись друг о друга и крутились в одну сторону, 
# Максвелл поместил между ними слои микроскопических «холостых шестерёнок» (крупиц электричества), 
# которые передают вращение.Когда мы подаем ток, эти шестерёнки начинают смещаться линейно — это полярный вектор. 
# Так Максвелл чисто механически открыл уравнения электромагнитного поля!


import numpy as np
import time

# =====================================================================
# ШАГ 1: ГИДРОДИНАМИЧЕСКАЯ СЕТКА ЭФИРА МАКСВЕЛЛА
# =====================================================================
class MaxwellEtherGrid:
    def __init__(self, size=15, elasticity=0.1, friction=0.05):
        """
        Инициализация упругой эфирной ткани.
        size: размер сетки ячеек (размерность пространства NxN)
        elasticity: коэффициент упругости эфирных связей
        friction: вязкое трение между ячейками-вихрями
        """
        self.size = size
        self.k = elasticity
        self.mu = friction
        
        # Сетка псевдо-векторов угловой скорости вращения ячеек (ось Z смотрит на нас)
        self.omega = np.zeros((size, size))
        
        # Сетка угловых ускорений (изменение вращения во времени)
        self.alpha = np.zeros((size, size))

    def apply_magnetic_impulse(self, x, y, strength=100.0):
        """ Раскручиваем центральную ячейку эфира псевдовектором силы """
        self.omega[x, y] = strength

    def update_physics_step(self, dt=0.1):
        """ 
        Математический расчет шага времени по оригинальной механике Максвелла.
        Каждая ячейка взаимодействует с 4 соседями (Сверху, Снизу, Слева, Справа).
        """
        new_omega = np.copy(self.omega)
        
        # Проходим по всем внутренним ячейкам сетки
        for i in range(1, self.size - 1):
            for j in range(1, self.size - 1):
                
                # Считаем разность вращения (крутящий момент) с соседними ячейками
                torque_x = (self.omega[i+1, j] - 2*self.omega[i, j] + self.omega[i-1, j])
                torque_y = (self.omega[i, j+1] - 2*self.omega[i, j] + self.omega[i, j-1])
                
                # Общий механический момент упругих сил (Дифференциальный оператор Лапласа)
                total_torque = self.k * (torque_x + torque_y)
                
                # Сила вязкого торможения эфирной жидкости
                damping = self.mu * self.omega[i, j]
                
                # Уравнение движения шестеренки: Ускорение = Момент - Торможение
                self.alpha[i, j] = total_torque - damping
                
                # Интегрируем скорость вращения во времени
                new_omega[i, j] += self.alpha[i, j] * dt
                
        self.omega = new_omega

# =====================================================================
# ШАГ 2: АНАЛИТИЧЕСКИЙ ОЧИСТИТЕЛЬ (Извлечение Максвелловского Ротора)
# =====================================================================
def extract_electromagnetic_wave(ether_grid):
    """
    Очиститель берет механические скорости вращения шестеренок и 
    вычисляет математический Ротор (Curl) поля скоростей. 
    По теории Максвелла, Ротор вращения механического эфира — это и есть Электрический Ток!
    """
    size = ether_grid.size
    current_density_E = np.zeros((size, size))
    
    # Вычисляем ротор (вихревой паттерн) пространственной сетки
    for i in range(1, size - 1):
        for j in range(1, size - 1):
            # Дискретный аналог ротора псевдовекторного поля
            curl_x = (ether_grid.omega[i, j+1] - ether_grid.omega[i, j-1]) / 2.0
            curl_y = (ether_grid.omega[i+1, j] - ether_grid.omega[i-1, j]) / 2.0
            
            # Напряженность индуцированного "электрического поля" в ячейке
            current_density_E[i, j] = np.sqrt(curl_x**2 + curl_y**2)
            
    return current_density_E

# =====================================================================
# ШАГ 3: ЗАПУСК СИМУЛЯЦИИ ЭФИРА В РЕАЛЬНОМ ВРЕМЕНИ
# =====================================================================
if __name__ == "__main__":
    print("====== ЗАПУСК КОМПЛЕКСА RE-PHYSICS: МОДУЛЬ МАКСВЕЛЛА (ЭФИР) ======")
    print("[Инфо]: Инициализируем ткань вакуума 15x15 механических ячеек...")
    
    # Создаем эфир
    ether = MaxwellEtherGrid(size=15, elasticity=0.2, friction=0.02)
    
    # Шаг 1: Раскручиваем ячейку в центре сетки (инжектируем псевдовектор вихря)
    center = 15 // 2
    print(f"[Импульс]: Начинаем вращение эфирной шестеренки в координатах [{center}, {center}]")
    ether.apply_magnetic_impulse(center, center, strength=50.0)
    
    print("[Симуляция]: Запуск динамики упругой среды на 5 шагов времени...")
    print("-" * 75)
    
    for step in range(1, 6):
        ether.update_physics_step(dt=0.2)
        
        # Запускаем очиститель: переводим механическое вращение в электромагнитную волну
        e_field = extract_electromagnetic_wave(ether)
        
        # Считаем суммарную энергию волны, родившейся из вращения шестеренок
        total_wave_energy = np.sum(e_field)
        
        print(f"Шаг {step}: Центральный вихрь передал вращение. Макс. скорость шестеренок = {np.max(ether.omega):.2f} рад/с")
        print(f"        [Очиститель данных]: Сгенерировано Электрическое поле (Энергия волны) = {total_wave_energy:.4f} у.е.")
        
        # Печатаем мини-карту центральной части сетки, чтобы увидеть, как расходится волна
        mini_map = ether.omega[center-2:center+3, center-2:center+3]
        print("        Фрагмент сетки вращения ячеек (5x5):")
        for row in mini_map:
            print("        " + " ".join(f"{val:>6.2f}" for val in row))
        print("-" * 75)
        time.sleep(0.3)
        
    print("\n✅ Вывод RE-PHYSICS:")
    print("Математическая очистка завершена. Код наглядно доказал:")
    print("Когда мы симулируем ложные механические шестеренки эфира Максвелла,")
    print("из чистого упругого трения ячеек (псевдовекторов) автоматически")
    print("выводятся уравнения волн электрического поля (полярных векторов).")
    print("Механическая ошибка превратилась в электродинамику!")

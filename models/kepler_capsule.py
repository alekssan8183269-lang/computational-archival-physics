import numpy as np

# ==============================================================================
# МОДУЛЬ: Kepler-Capsule-Emission (Вектор 1 + Метод F фреймворка RE-PHYSICS)
# ЭПИСТЕМЕ: Согласно Иоганну Кеплеру, Вселенная гармонизирована Платоновыми телами.
# Согласно Платону (метод F), зрение — это эмиссия лучей, исходящих из наблюдателя.
# Мы применяем эту архивную оптику "от обратного": пускаем лучи из центра атома Серы,
# запертого внутри Икосаэдра Алмаза. Если луч Платона встречает дефект или лакуну,
# система генерирует жесткий шоковый вольтаж (метод цифровых пустот).
# ==============================================================================

class KeplerCapsuleSimulator:
    def __init__(self):
        # Шаг 1: Генерируем идеальные 3D-координаты Икосаэдра Кеплера (12 вершин Алмаза)
        # Икосаэдр — золотое сечение геометрии, идеальная клетка для удержания Серы
        phi = (1 + np.sqrt(5)) / 2  # Золотая пропорция
        self.vertices_diamond = np.array([
            [-1,  phi,  0], [ 1,  phi,  0], [-1, -phi,  0], [ 1, -phi,  0],
            [ 0, -1,  phi], [ 0,  1,  phi], [ 0, -1, -phi], [ 0,  1, -phi],
            [ phi,  0, -1], [ phi,  0,  1], [-phi,  0, -1], [-phi,  0,  1]
        ])
        # Нормализуем радиус капсулы алмаза до 1.5 Ангстрем
        self.vertices_diamond = self.vertices_diamond / np.linalg.norm(self.vertices_diamond[0]) * 1.5

    def simulate_emission_optics(self, sulfur_displacement, matrix_defects):
        """
        Реализует Геометрическую экстрамиссию зрительных пространств (Метод F).
        sulfur_displacement: вектор смещения Серы из центра (x, y, z) — уродство структуры.
        matrix_defects: одномерный массив (12 элементов). 1 - связь цела, 0 - дефект решетки.
        """
        # Сера ('S') находится в центре капсулы, смещенная на микро-люфт
        sulfur_pos = np.array(sulfur_displacement)
        
        shock_voltage = 0.0
        ray_lengths = []
        
        # Платоновы лучи: пускаем 12 эмиссионных лучей из Серы к вершинам Алмаза
        for i in range(12):
            diamond_pos = self.vertices_diamond[i]
            
            # Вектор луча Платона
            ray_vector = diamond_pos - sulfur_pos
            distance = np.linalg.norm(ray_vector)
            ray_lengths.append(distance)
            
            # ⚡️ ШТРАФ 1: Асимметрия Кеплера. 
            # Если Сера съехала с центра, лучи становятся разной длины — нарушается музыка сфер.
            # Шарахаем током за дисбаланс сил удержания капсулы
            ideal_distance = 1.5
            if abs(distance - ideal_distance) > 0.01:
                shock_voltage += abs(distance - ideal_distance) * 800
                
            # ⚡️ ШТРАФ 2: Метод Цифровых Пустот (Лакуны в решетке)
            # Если в вершине Икосаэдра порвана связь (defect == 0), луч Платона 
            # улетает в бесконечную пустоту. Концентрация лакун взрывает "кристалл потерь".
            if matrix_defects[i] == 0:
                shock_voltage += 1200.0  # Максимальный разряд за сквозную дыру в капсуле!
                
        # Спектрально-волновое детектирование провалов: оцениваем стабильность
        ray_lengths = np.array(ray_lengths)
        variance = np.var(ray_lengths) # Дисперсия длин лучей
        
        # Если искажение формы (дисперсия) слишком велико — удваиваем вольтаж
        if variance > 0.05:
            shock_voltage *= 2.5
            
        return shock_voltage, variance


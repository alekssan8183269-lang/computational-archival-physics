# Создаем Модуль F: «Emission-Optics» (Зрительные лучи Платона и Евклида).
# Исторический бэкграунд (Археологический контекст)
# В античности Платон, Евклид и Птолемей разработали «теорию зрительных лучей» (экстрамиссию). 
# Они были убеждены, что зрение устроено обратно современным представлениям: 
# наши глаза сами испускают невидимый конический пучок лучей («щупальца света»), 
# которые с огромной скоростью ощупывают окружающие предметы и возвращают информацию в мозг.
# Хотя физически это абсолютно неверно, математически древние греки создали точную 
# геометрическую основу для алгоритма трассировки лучей (Ray Tracing) и работы 
# современных лидаров (LiDAR) в беспилотных автомобилях. 
# Беспилотник буквально работает по Платону: он сам испускает лучи из «глаз»-сенсоров, 
# ощупывая 3D-пространство перед собой.Золотая жила кодаМы пишем полноценный, 
# масштабный симулятор, который:Моделирует беспилотный автомобиль, едущий по дороге, 
# и препятствие (например, пешехода или стену).Генерирует «ошибочные» архивные лучи Платона, 
# бьющие из сенсора, накладывая на них реалистичный шум, 
# погрешности атмосферы и процентные ошибки измерений.Аналитический очиститель: 
# С помощью тригонометрических матриц (псевдовекторов углов обзора) и 
# фильтра Калмана/скользящего среднего очищает зашумленные древние лучи и с 
# пугающей точностью строит реальную 3D-карту препятствий перед машиной.
# Выводит красивый интерактивный 3D-график Plotly, который можно крутить мышкой.


import numpy as np
import plotly.graph_objects as go
import time

# ===================================================================================================
# #################################################################################################==
# ШАГ 1: ДВИЖОК ЗРИТЕЛЬНЫХ ЛУЧЕЙ ПЛАТОНА (Генератор зашумленных архивных данных)
# #################################################################################################==
# ИСХОДНЫЕ АРХИВНЫЕ РАБОТЫ: Платон, диалог «Тимей» (IV в. до н.э.); Евклид, «Оптика» (III в. до н.э.).
# КТО ИСПОЛЬЗОВАЛ: Античные геометры, архитекторы, оптики раннего Средневековья.
# ХАЙП ТОЙ ЭПОХИ: Модель идеально объясняла, почему мы не видим в темноте (глаз испускает лучи, но им
# нужна родственная среда — дневной свет, чтобы активировать 'ощупывание').
# ===================================================================================================

class PlatoEmissionLidar:
    def __init__(self, fov_degrees=60, num_rays=150):
        """
        Инициализация античного 'глаза-прожектора' для беспилотника.
        fov_degrees: угол обзора конуса зрения Платона
        num_rays: количество испускаемых лучей-'щупалец'
        """
        self.fov = np.radians(fov_degrees)
        self.num_rays = num_rays
        # Углы, под которыми глаз испускает лучи (векторная сетка обзора)
        self.ray_angles = np.linspace(-self.fov/2, self.fov/2, num_rays)
        
    def simulate_scene_with_noise(self, car_pos=0.0, obstacle_dist=12.0, obstacle_size=3.0, noise_pct=8.0):
        """
        Испускание лучей Платона в трехмерном пространстве.
        На данные накладывается случайный геометрический шум и процентная погрешность.
        """
        raw_distances = []
        true_distances = []
        
        # Моделируем препятствие впереди (например, стену/пешехода)
        # Истинная геометрия стены: находится на расстоянии obstacle_dist
        for angle in self.ray_angles:
            # Истинное расстояние по тригонометрическому лучу
            true_d = obstacle_dist / np.cos(angle)
            
            # Ограничиваем ширину препятствия по углам
            if abs(np.tan(angle) * obstacle_dist) > obstacle_size / 2:
                # Луч улетел в бесконечность (препятствия нет)
                true_d = 30.0 
                
            true_distances.append(true_d)
            
            # НАЛОЖЕНИЕ ШУМА И ПРОЦЕНТНОЙ ПОГРЕШНОСТИ
            # Шум атмосферы (например, туман или пыль для лидара)
            random_noise = np.random.normal(0, (noise_pct / 100.0) * true_d)
            # Систематическая погрешность затухания платоновского луча с расстоянием
            systemic_error = 0.03 * true_d 
            
            raw_d = true_d + random_noise + systemic_error
            # Ограничиваем физический предел дальности "взгляда"
            raw_d = np.clip(raw_d, 0.0, 30.0)
            raw_distances.append(raw_d)
            
        return np.array(true_distances), np.array(raw_distances)

# ===================================================================================================
# #################################################################################################==
# ШАГ 2: АНАЛИТИЧЕСКИЙ ОЧИСТИТЕЛЬ (Превращение геометрии Платона в LiDAR ИИ)
# #################################################################################################==
# АРХЕОЛОГИЧЕСКИЙ МЕТОД: Мы берем ложную идею 'лучей из глаз', но используем её математическую матрицу,
# чтобы рассчитать обратную задачу — воссоздать 3D-облако точек перед беспилотным автомобилем.
# Мы применяем статистическую фильтрацию для очистки процентной погрешности.
# ===================================================================================================

def clean_plato_rays_to_3d_cloud(angles, raw_distances, true_distances):
    """
    Очиститель преобразует полярные архивные координаты (угол, дистанция) в декартову 3D сетку (X, Y, Z).
    Применяет скользящий фильтр для подавления шума.
    """
    # Очистка шума методом пространственного сглаживания (Очиститель данных)
    cleaned_distances = np.copy(raw_distances)
    for i in range(2, len(raw_distances) - 2):
        # Берем среднее по 5 соседним лучам, убирая резкие выбросы
        cleaned_distances[i] = np.mean(raw_distances[i-2:i+3])
        
    # Перевод архивных лучей в реальные 3D координаты объектов
    # Ось X — ширина дороги, Ось Y — дистанция вперед, Ось Z — высота (моделируем плоскость дороги Z=0)
    x_raw = raw_distances * np.sin(angles)
    y_raw = raw_distances * np.cos(angles)
    
    x_clean = cleaned_distances * np.sin(angles)
    y_clean = cleaned_distances * np.cos(angles)
    
    x_true = true_distances * np.sin(angles)
    y_true = true_distances * np.cos(angles)
    
    # Считаем средний процент погрешности до и после очистки
    initial_error_pct = np.mean(np.abs(raw_distances - true_distances) / true_distances) * 100
    final_error_pct = np.mean(np.abs(cleaned_distances - true_distances) / true_distances) * 100
    
    return x_raw, y_raw, x_clean, y_clean, x_true, y_true, initial_error_pct, final_error_pct


    # Инициализация лидара Платона
    lidar = PlatoEmissionLidar(fov_degrees=70, num_rays=150)
    
    # Генерируем сцену (препятствие на 12 метрах, размер 4 метра)
    true_d, raw_d = lidar.simulate_scene_with_noise(obstacle_dist=12.0, obstacle_size=4.0, noise_pct=8.0)
    
    # Запуск очистителя
    x_r, y_r, x_c, y_c, x_t, y_t, err_start, err_end = clean_plato_rays_to_3d_cloud(lidar.ray_angles, raw_d, true_d)
    
    # Принты с подробной аналитикой погрешностей
    print(f" 📊 Статистический отчет археологии данных:")
    print(f" ------------------------------------------------------------------")
    print(f" -> Первоначальная средняя погрешность лучей Платона : {err_start:.2f}%")
    print(f" -> Погрешность после цифровой ИИ-очистки инвариантов: {err_end:.2f}%")
    print(f" -> Эффективность алгоритма очистки архивной модели  : Улучшение на {err_start - err_end:.2f}%")
    print(f" ------------------------------------------------------------------")

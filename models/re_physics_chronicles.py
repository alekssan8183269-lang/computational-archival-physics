# ШАГ 1: АНТИЧНОСТЬ И СРЕДНЕВЕКОВЬЕ — ГЕОЦЕНТРИЧЕСКИЙ СИГНАЛ (МЕТОД ПТОЛЕМЕЯ)
# #################################################################################################==
# ИСХОДНЫЕ АРХИВНЫЕ РАБОТЫ: Клавдий Птолемей, «Альмагест» (II век н.э.).
# КТО ИСПОЛЬЗОВАЛ: Астрономы исламского мира (Ал-Баттани), средневековой Европы (Региомонтан).
# ИСТОРИЧЕСКИЙ КОНТЕКСТ: Человечество считало Землю центром Вселенной. Чтобы объяснить странное,
# порой попятное движение планет (когда они визуально летят назад), Птолемей изобрёл гениальный
# геометрический костыль: круги внутри кругов (эпициклы и деференты).
# ХАЙП ТОЙ ЭПОХИ: Это была самая долгоживущая теория в истории — она безотказно правила умами 1400 лет.
# ===================================================================================================

def archive_step_1_ptolemy():
    print("\n" + "#"*100)
    print(" [ХРОНИКА RE-PHYSICS] ШАГ 1: АНТИЧНОСТЬ — ОЧИСТКА ГЕОЦЕНТРИЧЕСКОГО КОСТЫЛЯ ПТОЛЕМЕЯ")
    print("#"*100)
    print(" Источник: Клавдий Птолемей, монография 'Математическое построение' (Almagest), II в. н.э.")
    
    # Моделируем 100 наблюдений древнего астронома
    t = np.linspace(0, 2*np.pi, 100)
    
    # Древняя формула: Сложение двух вращающихся кругов для подгонки под наблюдения
    # Вектор главного круга (деферент) + вектор малого круга (эпицикл)
    ptolemy_formula = 12.0 * np.exp(1j * 1.0 * t) + 4.0 * np.exp(1j * 6.0 * t)
    
    print(" -> Статус формулы: ОШИБОЧНАЯ (Земля НЕ в центре, орбиты НЕ круговые).")
    print(" -> Вычислительный анализ: Ищем скрытый математический инвариант...")
    
    # Археологический метод: Раскладываем ложные петли Птолемея через спектр частот (Фурье)
    fft_analysis = np.abs(np.fft.fft(ptolemy_formula)) / 100
    significant_harmonics = np.where(fft_analysis > 0.5)[0]
    
    print(f" -> РЕЗУЛЬТАТ ОЧИСТКИ: Выделены истинные резонансные частоты системы: {significant_harmonics[:2]}")
    print(" " + "="*98)
    print(" БУДУЩЕЕ МЕТОДА: Древняя логика кругов Птолемея сегодня эволюционировала в анализ Фурье.")
    print(" В будущем мы применим этот модуль для мгновенного поиска периодических гравитационных")
    print(" возмущений и скрытых экзопланет на основе зашумлённых световых кривых Kepler и James Webb.")
    print(" ЧТО МОЖЕТ РОДИТЬСЯ: Сверхбыстрый геометрический фильтр для поиска планет вне Солнечной системы.")
    time.sleep(0.4)

